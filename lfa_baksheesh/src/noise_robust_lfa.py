"""
noise_robust_lfa.py
================================================================================
Robust Linked Fault Analysis (LFA) under Practical Noise & Unknown Fault Locations.

Implements the algorithms highlighted in the IIT Indore Research Poster:
1. Unknown Fault Location Identification:
   - Identifies the faulted nibble pair (i, j) with 100% accuracy for N >= 5
     ciphertexts via majority voting / variance elimination over all 32C2 = 496 pairs.
2. Missed Fault Noise Resilience:
   - Tolerates physical glitch miss rates up to p_miss = 30% with full master-key
     recovery achieved in N <= 30 attempts per relation.
================================================================================
"""

import random
from collections import Counter
from typing import List, Tuple, Optional, Dict
from .baksheesh import (
    encrypt, inv_perm_bits, add_constants, get_nibble, set_nibble,
    NUM_ROUNDS, MASK128
)
from .fault_sim import encrypt_with_linked_fault_last_round
from .ldfa_attack import recover_master_key_candidates


def identify_unknown_fault_pair(
    faulty_ciphertexts: List[int], num_rounds: int = NUM_ROUNDS
) -> Tuple[Tuple[int, int], int, float]:
    """
    Given N >= 5 faulty ciphertexts generated by an UNKNOWN linked fault pair (i*, j*),
    identifies the exact pair (i*, j*) and the leaked subkey difference esk[i*] ^ esk[j*].

    Evaluates all 32C2 = 496 candidate pairs.
    For the true pair (i*, j*), w'[i*] ^ w'[j*] = esk[i*] ^ esk[j*] is invariant (variance = 0)
    across all ciphertexts. For any wrong pair, the difference varies randomly with
    probability 16^(-N+1) of false coincidence.

    Returns:
        ((i_star, j_star), leaked_difference, confidence_ratio)
    """
    assert len(faulty_ciphertexts) >= 2, "At least 2 ciphertexts required for location discovery (5 recommended)."

    ac = add_constants(0, num_rounds)
    w_list = [inv_perm_bits(ct ^ ac) for ct in faulty_ciphertexts]
    N = len(w_list)

    best_pair = None
    best_diff = None
    best_consistency = -1.0

    candidate_invariant_pairs = []

    for i in range(32):
        for j in range(i + 1, 32):
            diffs = [get_nibble(w, i) ^ get_nibble(w, j) for w in w_list]
            counts = Counter(diffs)
            most_common_val, freq = counts.most_common(1)[0]
            consistency = freq / N

            if consistency == 1.0:
                candidate_invariant_pairs.append(((i, j), most_common_val, consistency))

            if consistency > best_consistency:
                best_consistency = consistency
                best_pair = (i, j)
                best_diff = most_common_val

    if candidate_invariant_pairs:
        # If exactly one pair is 100% consistent, return it directly
        return candidate_invariant_pairs[0]

    return best_pair, best_diff, best_consistency


def collect_noisy_faulty_ciphertexts(
    plaintext_list: List[int],
    master_key: int,
    target_i: int,
    target_j: int,
    p_miss: float = 0.30,
    num_rounds: int = NUM_ROUNDS
) -> List[int]:
    """
    Simulates a physical noisy fault injection channel.
    With probability (1 - p_miss), the glitch succeeds, producing a linked fault (target_i, target_j).
    With probability p_miss, the glitch misses (e.g. normal encryption or random bit-flip noise).
    """
    ciphertexts = []
    for pt in plaintext_list:
        if random.random() < p_miss:
            # Miss event: device executes normally
            ct = encrypt(pt, master_key, num_rounds=num_rounds)
        else:
            # Hit event: physical instruction skip produces linked fault
            ct, _ = encrypt_with_linked_fault_last_round(pt, master_key, target_i, target_j, num_rounds=num_rounds)
        ciphertexts.append(ct)
    return ciphertexts


def recover_difference_under_noise(
    ciphertexts: List[int],
    target_i: int,
    target_j: int,
    num_rounds: int = NUM_ROUNDS
) -> Tuple[int, int]:
    """
    Extracts the subkey difference esk[i] ^ esk[j] under noisy fault conditions
    using majority voting across N ciphertexts.

    Returns:
        (leaked_diff, vote_count)
    """
    ac = add_constants(0, num_rounds)
    diffs = []
    for ct in ciphertexts:
        w = inv_perm_bits(ct ^ ac)
        d = get_nibble(w, target_i) ^ get_nibble(w, target_j)
        diffs.append(d)

    counts = Counter(diffs)
    most_common_diff, vote_count = counts.most_common(1)[0]
    return most_common_diff, vote_count


def full_attack_under_noise(
    master_key: int,
    p_miss: float = 0.30,
    attempts_per_relation: int = 30,
    num_rounds: int = NUM_ROUNDS
) -> Tuple[bool, int, List[int]]:
    """
    Mounts full 128-bit key recovery under a noisy fault channel (p_miss <= 30%).
    Collects attempts_per_relation noisy ciphertexts for each of the 31 adjacent relations,
    filters noise via majority voting, reconstructs the 16 key candidates,
    and disambiguates with 1 known (P, C) pair.

    Returns:
        (success, recovered_master_key, delta_chain)
    """
    recovered_diffs = []

    for rel in range(31):
        pts = [random.getrandbits(128) for _ in range(attempts_per_relation)]
        cts = collect_noisy_faulty_ciphertexts(pts, master_key, rel, rel + 1, p_miss=p_miss, num_rounds=num_rounds)
        diff, _ = recover_difference_under_noise(cts, rel, rel + 1, num_rounds=num_rounds)
        recovered_diffs.append(diff)

    candidates = recover_master_key_candidates(recovered_diffs, num_rounds=num_rounds)

    # Disambiguate with 1 known pair
    v_pt = random.getrandbits(128)
    v_ct = encrypt(v_pt, master_key, num_rounds=num_rounds)

    matches = [cand for _, cand in candidates if encrypt(v_pt, cand, num_rounds=num_rounds) == v_ct]

    success = (len(matches) == 1 and matches[0] == master_key)
    recovered_key = matches[0] if matches else 0
    return success, recovered_key, recovered_diffs
